"""Интеграция Clatch — данные цикла из приватного API в Home Assistant."""
from __future__ import annotations

import datetime as dt

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import Platform
from homeassistant.core import HomeAssistant
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from .api import ClatchApiClient
from .const import CONF_PROFILE_ID, DEFAULT_SCAN_INTERVAL_MINUTES, DOMAIN
from .coordinator import ClatchDataUpdateCoordinator

PLATFORMS: list[Platform] = [Platform.SENSOR, Platform.BINARY_SENSOR]


async def async_setup_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
    session = async_get_clientsession(hass)
    client = ClatchApiClient(session, entry.data["token"], entry.data[CONF_PROFILE_ID])

    minutes = entry.options.get("scan_interval_minutes", DEFAULT_SCAN_INTERVAL_MINUTES)
    coordinator = ClatchDataUpdateCoordinator(hass, entry, client, dt.timedelta(minutes=minutes))
    await coordinator.async_config_entry_first_refresh()

    hass.data.setdefault(DOMAIN, {})[entry.entry_id] = coordinator
    entry.async_on_unload(entry.add_update_listener(_async_update_listener))

    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    return True


async def _async_update_listener(hass: HomeAssistant, entry: ConfigEntry) -> None:
    await hass.config_entries.async_reload(entry.entry_id)


async def async_unload_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
    unloaded = await hass.config_entries.async_unload_platforms(entry, PLATFORMS)
    if unloaded:
        hass.data[DOMAIN].pop(entry.entry_id)
    return unloaded
